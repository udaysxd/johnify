class UserLogin(BaseModel):
    user_email: EmailStr
    password: str

class UserResponse(UserBase):
    user_id: int
    uuid: UUID
    is_verified: bool
    created_on: datetime
    updated_on: datetime
    active: bool
    profile_pic_url: Optional[str] = None

